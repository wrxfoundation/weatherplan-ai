// 셀 견적: 월 요금(결합 할인 전) + 사은품(속도 기준 + TV 포함 가산 + 통신사 프로모션)
export function telcoCell(speed, tvKey, carrier) {
  const tv = TV_OPTIONS.find((t) => t.key === tvKey)
  const monthly = (SPEED_MAP[speed] ?? 0) + (tv?.add ?? 0)
  const gift = (GIFT_MAP[speed] ?? 0) + (tvKey !== 'solo' ? 50000 : 0) + (CARRIER_PROMO[carrier]?.giftAdd ?? 0)
  return { monthly, gift }
}

