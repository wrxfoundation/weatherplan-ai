/** 자급률 → 정성 라벨 */
export function selfSufficiencyLabel(ratio) {
  if (ratio == null) return null
  if (ratio >= 150) return '발전 잉여(여유 잠재 큼)'
  if (ratio >= 100) return '발전 잉여'
  if (ratio >= 70) return '소비 근접'
  return '소비 초과(계통 혼잡)'
}
