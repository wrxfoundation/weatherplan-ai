/** 시도 → 지역 송변전 인프라 집계(본부 단위, 통합 지역은 그대로 표기) */
export function substationForSido(sido) {
  const names = SIDO_HONBU[sido]
  if (!names) return null
  const rows = SUBSTATIONS.filter((r) => names.includes(r.region))
  if (!rows.length) return null
  const sum = (k) => rows.reduce((a, r) => a + r[k], 0)
  return {
    region: rows.map((r) => r.region).join('+'),
    n: sum('n'),
    hv: sum('hv'),
    n345: sum('n345'),
    n154: sum('n154'),
    hvMva: sum('hvMva'),
    grouped: rows.length > 1 || names.length === 1 ? rows.some((r) => /[·+]|충남|전남|울산/.test(r.region)) : false,
  }
}
