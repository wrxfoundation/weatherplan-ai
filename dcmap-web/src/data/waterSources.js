const EARTH_R = 6371
function km(lat1, lng1, lat2, lng2) {
  const rad = (d) => (d * Math.PI) / 180
  const dLat = rad(lat2 - lat1)
  const dLng = rad(lng2 - lng1)
  const a = Math.sin(dLat / 2) ** 2 + Math.cos(rad(lat1)) * Math.cos(rad(lat2)) * Math.sin(dLng / 2) ** 2
  return 2 * EARTH_R * Math.asin(Math.sqrt(a))
}

/** 최근접 주요 수원(댐) — { name, type, km, capMcm } | null. type: 다목적/용수. */
export function nearestWaterSource(lat, lng) {
  let best = null
  for (const [name, sLat, sLng, type, cap] of WATER_SOURCES) {
    const d = km(lat, lng, sLat, sLng)
    if (!best || d < best.km) best = { name, type: type === 'M' ? '다목적' : '용수', km: d, capMcm: cap }
  }
  return best
}
