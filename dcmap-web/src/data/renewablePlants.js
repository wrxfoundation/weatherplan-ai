const EARTH_R = 6371
function km(lat1,lng1,lat2,lng2){const rad=(d)=>d*Math.PI/180;const dLat=rad(lat2-lat1),dLng=rad(lng2-lng1);const a=Math.sin(dLat/2)**2+Math.cos(rad(lat1))*Math.cos(rad(lat2))*Math.sin(dLng/2)**2;return 2*EARTH_R*Math.asin(Math.sqrt(a))}

/** 최근접 재생발전단지 {name, type, km} 또는 null */
export function nearestRenewable(lat,lng){
  let best=null
  for(const [la,ln,t,n] of RENEWABLE_PLANTS){const d=km(lat,lng,la,ln);if(!best||d<best.km)best={name:n,type:t,km:d}}
  return best
}
