// 엑셀(CSV) 내보내기 — BOM 포함(한국어 엑셀 호환) · 다운로드도 감사 로그 대상 (호출부에서 기록)
export function downloadCsv(roster) {
  const esc = (v) => `"${String(v).replace(/"/g, '""')}"`;
  const csv = "﻿" + [roster.cols, ...roster.rows].map((r) => r.map(esc).join(",")).join("\r\n");
  const blob = new Blob([csv], { type: "text/csv;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = `${roster.file}-${new Date().toISOString().slice(0, 10)}.csv`;
  a.click();
  URL.revokeObjectURL(url);
}
