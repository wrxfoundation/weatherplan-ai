// 방문 유형 키 → 인원. 모르는 키는 안전한 쪽(2인)으로 떨어뜨린다.
const TWO = new Set(CREW_RULES.two.map((r) => r.key));
const ONE = new Set(CREW_RULES.one.map((r) => r.key));

export function crewFor(kind) {
  if (ONE.has(kind)) return 1;
  if (TWO.has(kind)) return 2;
  return 2; // 분류되지 않은 방문은 2인 — 판단이 안 서면 안전한 쪽
}

export function crewReason(kind) {
  const hit = [...CREW_RULES.two, ...CREW_RULES.one].find((r) => r.key === kind);
  return hit ? hit.why : "분류 전 방문이라 2인으로 배차합니다";
}

